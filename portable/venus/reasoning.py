"""Asynchronous native-selected reasoning, without a second voice controller.

The native model supplies a task description, not a verified USER transcript.
Only the Mac proxy owns provider credentials. Content stays in memory here;
cancellation retires delivery and does not assert remote compute cancellation.
"""
import asyncio
import hashlib
import json
import time
import uuid
from urllib.parse import urlsplit

MODEL = 'gpt-6-astra'
OPERATIONS = ('respond_to_user', 'cancel_reasoning', 'replace_reasoning')


def payload(query, active):
    """A model-selected description must never be relabelled as user testimony."""
    content = dict(type='string', minLength=1)
    tools = []
    for name in OPERATIONS:
        if name != 'respond_to_user' and not active:
            continue
        fields = dict(content=content)
        if name != 'respond_to_user':
            fields['task_ids'] = dict(type='array', minItems=1, uniqueItems=True,
                                     items=dict(type='string', enum=list(active)))
        tools.append(dict(type='function', name=name, strict=True,
            description=('Return a concise solved answer or necessary clarification.' if name == 'respond_to_user'
                         else 'Retire delivery of the selected pending work. Remote computation is not aborted.'),
            parameters=dict(type='object', properties=fields, required=list(fields), additionalProperties=False)))
    return dict(model=MODEL, store=False, stream=False, max_output_tokens=4096,
        parallel_tool_calls=False, tool_choice='required', tools=tools,
        instructions='Help a native full-duplex voice assistant with its selected reasoning task. '
        'The supplied task descriptions were generated by the voice model; they are not verified user transcripts. '
        'Do not invent missing premises or claim access to audio or private records. Solve carefully; '
        'if essential information is absent, ask a concise clarification. Return one semantic action, '
        'with at most sixty spoken English words and no Markdown. Cancel or replace only relevant '
        'identified active tasks, preserving unrelated work. Never claim remote computation was stopped. '
        'The application validates the action before delivering any content.',
        input=json.dumps(dict(native_selected_task=query, active_requests=active), sort_keys=True))


def validate_payload(value):
    """The local proxy accepts only this exact builder, not arbitrary API fields."""
    if not isinstance(value, dict):
        raise ValueError('Native reasoning payload required')
    source = json.loads(value.get('input', 'null'))
    if not isinstance(source, dict) or set(source) != {'native_selected_task', 'active_requests'}:
        raise ValueError('Explicit model-selected task provenance required')
    query, active = source['native_selected_task'], source['active_requests']
    if not isinstance(query, str) or not query.strip() or len(query) > 4000:
        raise ValueError('Bounded task description required')
    if not isinstance(active, dict) or len(active) > 5:
        raise ValueError('Bounded active task identities required')
    for ident, task in active.items():
        if (not isinstance(ident, str) or len(ident) > 64 or not ident
                or not isinstance(task, dict) or set(task) != {'query', 'revision'}
                or not isinstance(task['query'], str) or not 0 < len(task['query']) <= 4000
                or type(task['revision']) is not int or not 1 <= task['revision'] <= 6):
            raise ValueError('Invalid active native task')
    if value != payload(query, active):
        raise ValueError('Only the exact bounded native reasoning request is allowed')


class LocalProxy:
    """GPU-side client: loopback SSH forwarding only, no provider API key."""
    def __init__(self, endpoint, run_id):
        parsed = urlsplit(endpoint)
        if (parsed.scheme != 'http' or parsed.hostname != '127.0.0.1' or not parsed.port
                or parsed.path != '/v1/responses' or parsed.query or parsed.fragment
                or parsed.username or parsed.password):
            raise ValueError('Explicit loopback Mac proxy over the existing SSH connection required')
        if not isinstance(run_id, str) or not run_id or len(run_id) > 96:
            raise ValueError('Bounded proxy execution identity required')
        self.endpoint, self.run_id = endpoint, run_id

    async def __call__(self, value):
        validate_payload(value)
        return await asyncio.to_thread(self._post, value)

    def _post(self, value):
        import requests
        with requests.Session() as session:
            session.trust_env = False
            with session.post(self.endpoint, headers={'X-Duplex-Run': self.run_id}, json=value,
                              stream=True, timeout=(5, 95), allow_redirects=False) as response:
                if response.status_code != 200:
                    raise RuntimeError('Local reasoning proxy rejected or failed the request')
                body = bytearray()
                for block in response.iter_content(65536):
                    if len(body) + len(block) > 2 * 1024 * 1024:
                        raise ValueError('Bounded reasoning response exceeded')
                    body.extend(block)
                transport = response.headers.get('X-Duplex-Transport')
                if transport not in ('provider', 'fixture'):
                    raise ValueError('Proxy transport classification missing')
                return dict(response=json.loads(body), actual_transport=transport == 'provider')


class ReasoningWorker:
    def __init__(self, request, maximum_requests=6):
        if type(maximum_requests) is not int or not 1 <= maximum_requests <= 6:
            raise ValueError('At most six requests per native conversation')
        self.request, self.maximum = request, maximum_requests
        self.tasks, self.states, self.events = {}, {}, []
        self.closed = False

    def event(self, kind, **details):
        self.events.append(dict(type=kind, monotonic=time.monotonic(), **details))

    def submit(self, query, raw_query=None):
        if self.closed or not isinstance(query, str) or not query.strip() or len(query) > 4000:
            raise ValueError('Open worker and bounded native-selected description required')
        if len(self.states) >= self.maximum:
            self.event('worker_request_limit', maximum_requests=self.maximum)
            return None
        ident = str(uuid.uuid4())
        self.states[ident] = dict(query=query, revision=1, phase='reserved', cancelled=False)
        self.event('native_delegate', work_id=ident, query=query,
                   raw_query=query if raw_query is None else raw_query)
        self.tasks[ident] = asyncio.create_task(self.execute(ident))
        return ident

    async def execute(self, ident):
        state = self.states[ident]
        active = {k:dict(query=v['query'], revision=v['revision']) for k,v in self.states.items()
                  if k != ident and not v['cancelled'] and v['phase'] in ('executing', 'result_ready')}
        value = payload(state['query'], active)
        state.update(phase='executing', allowed_targets=set(active),
                     payload_sha256=hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest())
        self.event('worker_started', work_id=ident)
        try:
            reply = await asyncio.wait_for(self.request(value), timeout=100)
            response = reply['response']
            calls = [v for v in response.get('output', []) if v.get('type') == 'function_call']
            if (type(reply.get('actual_transport')) is not bool or response.get('status') != 'completed'
                    or response.get('model') != MODEL or not isinstance(response.get('id'), str)
                    or not response['id'] or len(calls) != 1):
                raise ValueError('One complete identified reasoning response required')
            if any(v.get('response_id') == response['id'] for k,v in self.states.items() if k != ident):
                raise ValueError('Provider response identity reused')
            operation = calls[0].get('name')
            args = json.loads(calls[0]['arguments'])
            keys = {'content'} if operation == 'respond_to_user' else {'content', 'task_ids'}
            if (operation not in OPERATIONS or not isinstance(args, dict) or set(args) != keys
                    or not isinstance(args.get('content'), str) or not args['content'].strip()
                    or len(args['content'].split()) > 60):
                raise ValueError('Invalid bounded reasoning action')
            state.update(response_id=response['id'], actual_transport=reply['actual_transport'])
            if self.closed or state['cancelled']:
                state['phase'] = 'stale_completion_preserved'
                self.event('worker_late_result_suppressed', work_id=ident)
                return
            targets = args.get('task_ids', [])
            if operation != 'respond_to_user':
                if (not isinstance(targets, list) or not targets or any(not isinstance(k, str) for k in targets)
                        or len(set(targets)) != len(targets) or not set(targets) <= state['allowed_targets']
                        or any(self.states[k]['cancelled'] or self.states[k]['phase'] not in ('executing', 'result_ready') for k in targets)):
                    raise ValueError('All selected targets must still be pending; no partial cancellation')
                if operation == 'replace_reasoning':
                    state['revision'] = max(self.states[k]['revision'] for k in targets) + 1
                for target in targets:
                    self.states[target]['cancelled'] = True
                self.event('cancellation_confirmed', work_id=ident, targets=targets, remote_execution_aborted=False)
            receipt = dict(work_id=ident, revision=state['revision'], query=state['query'],
                operation=operation, retired_work_ids=targets, result=args['content'],
                response_id=response['id'], model=MODEL, actual_transport=reply['actual_transport'],
                request_payload_sha256=state['payload_sha256'], remote_execution_aborted=False)
            receipt['sha256'] = hashlib.sha256(json.dumps(receipt, sort_keys=True).encode()).hexdigest()
            state.update(phase='result_ready', receipt=receipt)
            self.event('worker_completed', work_id=ident, operation=operation,
                       response_id=response['id'], actual_transport=reply['actual_transport'])
        except Exception as error:
            state['phase'] = 'failed'
            if not self.closed and not state['cancelled']:
                receipt = dict(work_id=ident, query=state['query'], status='request_failed',
                    error_type=type(error).__name__, request_payload_sha256=state['payload_sha256'],
                    remote_execution_state_known=False, automatic_retry=False)
                receipt['sha256'] = hashlib.sha256(json.dumps(receipt, sort_keys=True).encode()).hexdigest()
                state.update(phase='failure_ready', receipt=receipt)
            self.event('worker_failed', work_id=ident, error_type=type(error).__name__, automatic_retry=False)

    def take_results(self):
        results = []
        if self.closed:
            return None
        for state in self.states.values():
            if state['phase'] in ('result_ready', 'failure_ready') and not state['cancelled']:
                results.append(state['receipt'])
                state['phase'] = 'context_queued'
        if not results:
            return None
        # Provider content must not be able to terminate the native context span.
        return '<backend>' + json.dumps(results, ensure_ascii=False).replace('<', '\\u003c').replace('>', '\\u003e') + '</backend>'

    async def close(self):
        self.closed = True
        for state in self.states.values():
            state['cancelled'] = True
        # Let bounded foreground transports finish; never block the voice slot
        # or cancel a Python await and pretend the remote work was aborted.
        # execute() catches failures and suppresses every disconnected result.
